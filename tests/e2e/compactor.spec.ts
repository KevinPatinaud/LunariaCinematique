import {test,expect,_electron,type ElectronApplication} from '@playwright/test';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
test('level ten, retreat objective and editable pushing settings survive saving and reopening',async()=>{
 test.setTimeout(90000);
 const dir=await fs.mkdtemp(path.join(os.tmpdir(),'lunaria-compactor-'));
 const file=path.join(dir,'compactor.game.json'),profile=path.join(dir,'profile');
 await fs.mkdir(profile);
 await fs.copyFile('C:/dev/Lunaria/HISTOIRE DE LUNARIA/Cinematiques studio/lunaria.game.json',file);
 const sourceBoss=JSON.parse(await fs.readFile(file,'utf8')).balance.enemies.find((e:{id:string})=>e.id==='compactor');
 await fs.writeFile(path.join(profile,'settings.json'),JSON.stringify({libraryRoot:'C:/dev/Lunaria/LunariaArtLibrary'}));
 await fs.writeFile(path.join(profile,'game-recents.json'),JSON.stringify([{path:file,title:'Lunaria',updatedAt:new Date().toISOString()}]));
 const env={...process.env,LUNARIA_E2E:'1',LUNARIA_TEST_USER_DATA:profile};delete env.LUNARIA_DEV_URL;
 let app:ElectronApplication|undefined;
 try{
  app=await _electron.launch({args:[ROOT],env:env as Record<string,string>});
  const page=await app.firstWindow(),errors:string[]=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.waitForURL('app://studio/index.html');
  await app.evaluate(({dialog},file)=>{
   dialog.showOpenDialog=async()=>({canceled:false,filePaths:[file]});
   dialog.showSaveDialog=async()=>({canceled:false,filePath:file});
   dialog.showMessageBox=async()=>({response:1,checkboxChecked:false});
  },file);
  await page.locator('.studio-sections').getByRole('button',{name:/^Niveaux/}).click();
  await page.locator('.gd-level-items').getByRole('button',{name:/10 - Faire reculer l’acier/}).click();
  await page.getByRole('navigation',{name:'Édition du niveau'}).getByRole('button',{name:'Paramètres',exact:true}).click();
  await expect(page.getByLabel('Objectif du niveau')).toHaveValue('repel_boss');
  await expect(page.getByLabel('Consigne du niveau')).toContainText('Interrompez les poussées du Compresseur');
  const out=process.env.COMPACTOR_ARTIFACT_DIR??path.join(ROOT,'work','compactor');
  await fs.mkdir(out,{recursive:true});
  await page.getByLabel('Objectif du niveau').scrollIntoViewIfNeeded();
  await page.screenshot({path:path.join(out,'studio-niveau-10.png')});
  await page.locator('.studio-sections').getByRole('button',{name:/^Ennemis/}).click();
  await page.locator('.gd-catalog').getByRole('button',{name:/^Le Compresseur/}).click();
  await page.getByRole('navigation',{name:'Fiche de Le Compresseur'}).getByRole('button',{name:'Règles du plateau',exact:true}).click();
  await expect(page.getByLabel('Poussées et surchauffe',{exact:true})).toBeChecked();
  await expect(page.getByLabel('Poussées à interrompre',{exact:true})).toHaveValue('3');
  await expect(page.getByLabel('Dégâts bruts par poussée',{exact:true})).toContainText('39 → 52 → 65');
  await expect(page.getByLabel('Graines par poussée interrompue',{exact:true})).toHaveValue(String(sourceBoss.rules.pushing.seedReward??0));
  await page.getByLabel('Graines par poussée interrompue',{exact:true}).fill('73');
  await page.getByLabel('Graines par poussée interrompue',{exact:true}).press('Tab');
  await page.getByLabel('Résistance par poussée',{exact:true}).scrollIntoViewIfNeeded();
  await page.screenshot({path:path.join(out,'studio-compresseur.png')});
  await expect(page.getByLabel('Canettes par autre allée au début d’une poussée',{exact:true})).toHaveValue('2');
  await page.getByLabel('Canettes par autre allée au début d’une poussée',{exact:true}).fill('3');
  await page.getByLabel('Intervalle des renforts d’escorte (s)',{exact:true}).fill('7');
  await page.getByLabel('Résistance par poussée',{exact:true}).fill('321');
  await page.getByLabel('Résistance par poussée',{exact:true}).press('Tab');
  await page.getByRole('navigation',{name:'Fiche de Le Compresseur'}).getByRole('button',{name:'Animations et sons de Le Compresseur',exact:true}).click();
  const attack=page.getByRole('article',{name:'Action : Attaque',exact:true});
  await expect(attack.getByLabel('Animation pour Attaque',{exact:true})).toHaveValue('compactor_attack');
  await expect(attack).toContainText('Départ après 0.405 s');
  await attack.getByRole('button',{name:'Modifier ici',exact:true}).click();
  await expect(page.getByLabel('Mouvement',{exact:true})).toHaveValue('press');
  await expect(page.getByLabel('Durée totale (s)',{exact:true})).toHaveValue('0.9');
  const time=page.getByLabel('Curseur temporel de l’animation',{exact:true});
  const drumProjection=page.locator('[data-rolling-drum="true"]');
  await expect(drumProjection).toHaveCount(1);
  const restDrum=await drumProjection.locator('image').first().getAttribute('transform');
  await time.fill('0.405');
  await expect(drumProjection.locator('image').first()).not.toHaveAttribute('transform',restDrum!);
  const stroke=page.getByLabel('Aperçu de l’animation',{exact:true}).locator(':scope > g').first();
  await expect(stroke).toHaveAttribute('transform',/translate\(-18,/);
  await expect(page.locator('[data-rolling-part="0"] > g')).toHaveAttribute('transform',/rotate\(-[0-9.]+\)/);
  await page.getByLabel('Aperçu de l’animation',{exact:true}).scrollIntoViewIfNeeded();
  await page.screenshot({path:path.join(out,'studio-attaque.png')});
  await page.getByText('Profils, actions spéciales et image de repos',{exact:true}).click();
  await page.getByText('Image de repos et dimensions',{exact:true}).click();
  await page.getByText('Roues et roulement',{exact:true}).click();
  await expect(page.getByLabel('Centre x de la roue 1',{exact:true})).toHaveValue('0.917');
  await page.getByLabel('Rayon x de la roue 1',{exact:true}).fill('0.026');
  await page.getByLabel('Rayon x de la roue 1',{exact:true}).press('Tab');
  await page.screenshot({path:path.join(out,'studio-roulement.png')});
  await page.getByText('Rouleaux cylindriques',{exact:true}).click();
  await expect(page.getByLabel('Rouleau 1 · gauche · haut x',{exact:true})).toHaveValue('0.204');
  await page.getByLabel('Rouleau 1 · gauche · haut x',{exact:true}).fill('0.205');
  await page.getByLabel('Rouleau 1 · gauche · haut x',{exact:true}).press('Tab');
  await page.screenshot({path:path.join(out,'studio-rouleau.png')});
  await page.getByRole('button',{name:'Enregistrer le projet',exact:true}).click();
  await expect(page.locator('.studio-project-state')).toContainText('Projet enregistré');
  const saved=JSON.parse(await fs.readFile(file,'utf8'));
  expect(saved.balance.enemies.find((e:{id:string})=>e.id==='compactor').rules.pushing.pressure).toBe(321);
  expect(saved.balance.enemies.find((e:{id:string})=>e.id==='compactor').rules.pushing.seedReward).toBe(73);
  expect(saved.balance.enemies.find((e:{id:string})=>e.id==='compactor').rules.pushing.escortCount).toBe(3);
  expect(saved.balance.enemies.find((e:{id:string})=>e.id==='compactor').rules.pushing.escortInterval).toBe(7);
  expect(saved.balance.enemies.find((e:{id:string})=>e.id==='compactor').visual.rollingParts[0].radius.x).toBe(.026);
  expect(saved.balance.enemies.find((e:{id:string})=>e.id==='compactor').visual.rollingDrums[0].left.top.x).toBe(.205);
  expect(saved.campaign.steps.at(-1).cinematicId).toBe('film_nursery_11');
  expect(errors).toEqual([]);
  await app.evaluate(({BrowserWindow})=>{for(const w of BrowserWindow.getAllWindows())w.destroy();});
  await app.close();
  app=await _electron.launch({args:[ROOT],env:env as Record<string,string>});
  const reopened=await app.firstWindow();await reopened.waitForURL('app://studio/index.html');
  await reopened.locator('.studio-sections').getByRole('button',{name:/^Ennemis/}).click();
  await reopened.locator('.gd-catalog').getByRole('button',{name:/^Le Compresseur/}).click();
  await reopened.getByRole('navigation',{name:'Fiche de Le Compresseur'}).getByRole('button',{name:'Règles du plateau',exact:true}).click();
  await expect(reopened.getByLabel('Résistance par poussée',{exact:true})).toHaveValue('321');
  await expect(reopened.getByLabel('Graines par poussée interrompue',{exact:true})).toHaveValue('73');
  await expect(reopened.getByLabel('Intervalle des renforts d’escorte (s)',{exact:true})).toHaveValue('7');
  await expect(reopened.getByLabel('Canettes par autre allée au début d’une poussée',{exact:true})).toHaveValue('3');
  await reopened.getByRole('navigation',{name:'Fiche de Le Compresseur'}).getByRole('button',{name:'Animations et sons de Le Compresseur',exact:true}).click();
  await reopened.getByText('Profils, actions spéciales et image de repos',{exact:true}).click();
  await reopened.getByText('Image de repos et dimensions',{exact:true}).click();
  await reopened.getByText('Rouleaux cylindriques',{exact:true}).click();
  await expect(reopened.getByLabel('Rouleau 1 · gauche · haut x',{exact:true})).toHaveValue('0.205');
 }finally{
  if(app){await app.evaluate(({BrowserWindow})=>{for(const w of BrowserWindow.getAllWindows())w.destroy();}).catch(()=>{});await app.close();}
  // Only this exact mkdtemp directory is removed.
  if(!path.resolve(dir).startsWith(path.resolve(os.tmpdir())+path.sep)||!path.basename(dir).startsWith('lunaria-compactor-'))throw Error('Unsafe temp path');
  await fs.rm(dir,{recursive:true,force:true,maxRetries:10,retryDelay:200});
 }
});
